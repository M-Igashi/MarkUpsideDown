export type IconName = keyof typeof ICONS;

/** Inline SVG markup for a 24-unit Lucide icon drawn at `size` px. */
export function icon(name: IconName, size = 16): string {
  return `<svg class="icon" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${ICONS[name]}</svg>`;
}

/** Fill every `[data-icon]` element under `root` with its icon (static markup in index.html). */
export function hydrateIcons(root: ParentNode = document) {
  for (const el of root.querySelectorAll<HTMLElement>("[data-icon]")) {
    el.insertAdjacentHTML(
      "afterbegin",
      icon(el.dataset.icon as IconName, Number(el.dataset.iconSize) || 16),
    );
    delete el.dataset.icon;
    if (!el.textContent?.trim() && el.title) el.setAttribute("aria-label", el.title);
  }
}
